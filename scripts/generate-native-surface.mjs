export function buildNativeSurface(root = process.cwd()) {
  const read = (file) => readFileSync(path.join(root, file), 'utf8');

  const capacitorSource = read('capacitor.config.ts');
  const manifestSource = read('android/app/src/main/AndroidManifest.xml');
  const capacitor = parseCapacitorConfig(capacitorSource);
  const identity = parseAndroidIdentity(read('android/app/build.gradle'));
  const sdk = parseSdkVersions(read('android/variables.gradle'));
  const behaviour = parseManifestBehaviour(manifestSource);
  const facts = readWebViewFacts(root, { capacitor, capacitorSource, manifestSource, namespace: identity.namespace });

  return {
    schemaVersion: SCHEMA_VERSION,
    note:
      'Generated by scripts/generate-native-surface.mjs from capacitor.config.ts, android/variables.gradle, android/app/build.gradle and AndroidManifest.xml, and - for webViewCapabilities - from the Android theme and colour resources, MainActivity and Capacitor\'s bridge source, package.json, the app\'s export, share-link, clipboard and back-button code, and the app-config table in docs/release-contract.json. Do not edit by hand. The permission NAMES are owned by scripts/check-support-claims.mjs, which guards them against the /supported screen in both directions; only the count appears here.',
    platforms: {
      android:
        'supported - built and signed by release-android.yml on every release, and proven on the Android emulator by hand, not on a phone: what was proven, and when, is in androidVerification; how the APK differs from the website is in webViewCapabilities',
      ios: 'the PWA only. The native project was dropped 2026-09-20 (869f13c92); see docs/ios-platform-footprint.md',
      web: 'verified',
    },
    androidVerification: ANDROID_VERIFICATION,
    capacitor,
    android: { ...identity, ...sdk, ...behaviour },
    webViewCapabilities: buildWebViewCapabilities(facts),
    distribution: {
      channel: 'github-release-sideload',
      what: 'release-android.yml builds a signed APK and attaches it to a GitHub Release',
      consequence:
        'not a store, so the app updates itself through apk-updater.plugin.ts, which is why REQUEST_INSTALL_PACKAGES is requested at all',
      decidedAt: '2026-09-21 - the owner declined Google Play (869f13d9r)',
    },
    permissionsOwnedBy: 'scripts/check-support-claims.mjs',
  };
}

function main(argv) {
  const check = argv.includes('--check');
  const root = process.cwd();
  const surface = buildNativeSurface(root);
  const problems = checkNativeSurface(surface);

  if (problems.length > 0) {
    console.error(`[native-surface] ${problems.length} problem(s):`);
    for (const problem of problems) console.error(`- ${problem}`);
    process.exitCode = 1;
    return;
  }

  const serialized = `${JSON.stringify(surface, null, 2)}\n`;
  const outputPath = path.join(root, OUTPUT_PATH);

  if (check) {
    let current = '';
    try {
      current = readFileSync(outputPath, 'utf8');
    } catch {
      current = '';
    }

    if (current !== serialized) {
      console.error(`[native-surface] ${OUTPUT_PATH} is stale. Run \`npm run native:surface\`.`);
      process.exitCode = 1;
      return;
    }

    const enabled = surface.capacitor.plugins.flatMap((p) => p.providers.filter((x) => x.enabled).map((x) => x.provider));

    console.log(
      `[native-surface] OK - ${surface.capacitor.appId}, ${surface.capacitor.plugins.length} plugin(s), ` +
        `${enabled.length} provider(s) enabled (${enabled.join(', ')}), ${surface.android.permissionCount} permission(s), ` +
        `${surface.webViewCapabilities.length} WebView capabilities.`,
    );
    return;
  }

  writeFileSync(outputPath, serialized, 'utf8');
  console.log(`[native-surface] wrote ${OUTPUT_PATH}.`);
}

if (import.meta.url === pathToFileURL(process.argv[1] ?? '').href) {
  main(process.argv.slice(2));
}
