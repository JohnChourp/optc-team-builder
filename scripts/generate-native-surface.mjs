#!/usr/bin/env node
/**
 * 869f13d80. Writes the native surface record from the native projects, and checks it.
 *
 * Generated from `capacitor.config.ts`, `android/variables.gradle`,
 * `android/app/build.gradle` and the Android manifest - never hand-listed, because the
 * point of the task is that five files held one surface and nothing summarised it.
 *
 * The permission list is cited rather than copied: `check-support-claims.mjs` already
 * generates it from the manifest and fails in both directions against the `/supported`
 * screen. Only the COUNT appears here, so this record and that guard cannot disagree about
 * the names.
 *
 * Run: npm run native:surface
 */
import { readFileSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import process from 'node:process';
import { pathToFileURL } from 'node:url';

import {
  checkNativeSurface,
  parseAndroidIdentity,
  parseCapacitorConfig,
  parseManifestBehaviour,
  parseSdkVersions,
} from './lib/native-surface.mjs';

const OUTPUT_PATH = 'docs/native-surface.json';
export const SCHEMA_VERSION = 1;

export function buildNativeSurface(root = process.cwd()) {
  const read = (file) => readFileSync(path.join(root, file), 'utf8');

  const capacitor = parseCapacitorConfig(read('capacitor.config.ts'));
  const identity = parseAndroidIdentity(read('android/app/build.gradle'));
  const sdk = parseSdkVersions(read('android/variables.gradle'));
  const behaviour = parseManifestBehaviour(read('android/app/src/main/AndroidManifest.xml'));

  return {
    schemaVersion: SCHEMA_VERSION,
    note:
      'Generated by scripts/generate-native-surface.mjs from capacitor.config.ts, android/variables.gradle, android/app/build.gradle and AndroidManifest.xml. Do not edit by hand. The permission NAMES are owned by scripts/check-support-claims.mjs, which guards them against the /supported screen in both directions; only the count appears here.',
    platforms: {
      android: 'supported - builds automatically, proven to work by hand',
      ios: 'the PWA only. The native project was dropped 2026-09-20 (869f13c92); see docs/ios-platform-footprint.md',
      web: 'verified',
    },
    capacitor,
    android: { ...identity, ...sdk, ...behaviour },
    distribution: {
      channel: 'github-release-sideload',
      what: 'release-android.yml builds a signed APK and attaches it to a GitHub Release',
      consequence:
        'not a store, so the app updates itself through apk-updater.plugin.ts, which is why REQUEST_INSTALL_PACKAGES is requested at all',
      decidedAt: '2026-09-21 - the owner declined Google Play (869f13d9r)',
    },
    permissionsOwnedBy: 'scripts/check-support-claims.mjs',
  };
}

function main(argv) {
  const check = argv.includes('--check');
  const root = process.cwd();
  const surface = buildNativeSurface(root);
  const problems = checkNativeSurface(surface);

  if (problems.length > 0) {
    console.error(`[native-surface] ${problems.length} problem(s):`);
    for (const problem of problems) console.error(`- ${problem}`);
    process.exitCode = 1;
    return;
  }

  const serialized = `${JSON.stringify(surface, null, 2)}\n`;
  const outputPath = path.join(root, OUTPUT_PATH);

  if (check) {
    let current = '';
    try {
      current = readFileSync(outputPath, 'utf8');
    } catch {
      current = '';
    }

    if (current !== serialized) {
      console.error(`[native-surface] ${OUTPUT_PATH} is stale. Run \`npm run native:surface\`.`);
      process.exitCode = 1;
      return;
    }

    const enabled = surface.capacitor.plugins.flatMap((p) => p.providers.filter((x) => x.enabled).map((x) => x.provider));

    console.log(
      `[native-surface] OK - ${surface.capacitor.appId}, ${surface.capacitor.plugins.length} plugin(s), ` +
        `${enabled.length} provider(s) enabled (${enabled.join(', ')}), ${surface.android.permissionCount} permission(s).`,
    );
    return;
  }

  writeFileSync(outputPath, serialized, 'utf8');
  console.log(`[native-surface] wrote ${OUTPUT_PATH}.`);
}

if (import.meta.url === pathToFileURL(process.argv[1] ?? '').href) {
  main(process.argv.slice(2));
}
