#!/usr/bin/env node
/**
 * 869f13d7j / 869f13d7n. Writes what a release moves and what it produces, and checks it.
 *
 * The version half is MEASURED, not declared: it bumps a fixture of the real tree in a
 * temp directory and diffs. That is the whole point - `FAQ.md` carried "eight version keys
 * across five files" for the days after `ios/` was dropped, because nothing re-derived it.
 *
 * `--check` compares instead of writing, and fails when a field moves with no recorded
 * rule, when a recorded field has stopped moving, or when an artifact's producer no longer
 * contains the step that makes it.
 *
 * 869f63gu4. It also derives which `app-config.js` each build gets - the key x build target
 * table in `appConfigByBuildTarget` - and writes its readable half into the generated section
 * of `docs/release-secrets-register.md`. `--check` fails when a workflow's build environment,
 * the writer or the npm script chain changes without the table following.
 *
 * Run: npm run release:contract
 */
import { execFileSync } from 'node:child_process';
import { cpSync, mkdtempSync, mkdirSync, readFileSync, rmSync, writeFileSync } from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import process from 'node:process';
import { pathToFileURL } from 'node:url';

import {
  formatAppConfigTargetsMarkdown,
  readAppConfigTargets,
  replaceAppConfigSection,
} from './lib/app-config-targets.mjs';
import {
  AUTOMATIC_OUTPUT_SIGNATURES,
  MANUAL_OUTPUTS,
  buildVersionFields,
  checkReleaseContract,
} from './lib/release-contract.mjs';

const OUTPUT_PATH = 'docs/release-contract.json';
const SECRETS_REGISTER_PATH = 'docs/release-secrets-register.md';
export const SCHEMA_VERSION = 1;

const TRACKED_FILES = [
  'package.json',
  'package-lock.json',
  'android/app/build.gradle',
  'src/app/core/data/app-version.data.ts',
  'scripts/bump-version.sh',
];

const PRODUCER_FILES = ['scripts/release-and-tag.sh', '.github/workflows/release-android.yml'];

/** Which `key: value` pairs a real bump rewrites, and how many sites each has. */
export function measureVersionFields(root = process.cwd()) {
  const work = mkdtempSync(path.join(os.tmpdir(), 'optc-release-contract-'));

  try {
    for (const file of TRACKED_FILES) {
      const target = path.join(work, file);
      mkdirSync(path.dirname(target), { recursive: true });
      cpSync(path.join(root, file), target);
    }

    const before = new Map(TRACKED_FILES.map((f) => [f, readFileSync(path.join(work, f), 'utf8')]));

    execFileSync('bash', [path.join(work, 'scripts/bump-version.sh'), '--bump', 'patch'], {
      cwd: work,
      stdio: 'pipe',
    });

    const fields = [];

    for (const file of TRACKED_FILES) {
      const after = readFileSync(path.join(work, file), 'utf8');
      const start = before.get(file);
      if (after === start) continue;

      // Count changed lines per key, so package-lock's two `version` sites are visible.
      const beforeLines = start.split('\n');
      const counts = new Map();

      after.split('\n').forEach((line, index) => {
        if (line === beforeLines[index]) return;
        const match =
          line.match(/"(version)"\s*:/u) ||
          line.match(/\b(versionCode|versionName)\b/u) ||
          line.match(/export const (APP_VERSION)\b/u);
        if (!match) return;
        const key = match[1];
        counts.set(key, (counts.get(key) ?? 0) + 1);
      });

      for (const [key, valueSites] of counts) {
        fields.push({ file, key, valueSites });
      }
    }

    return fields;
  } finally {
    rmSync(work, { recursive: true, force: true });
  }
}

export function buildReleaseContract(root = process.cwd(), appConfig = readAppConfigTargets(root)) {
  const versionFields = buildVersionFields(measureVersionFields(root));

  return {
    schemaVersion: SCHEMA_VERSION,
    note:
      'Generated by scripts/generate-release-contract.mjs. The version fields are MEASURED by bumping a fixture of the real tree, never hand-listed. Do not edit by hand.',
    versionFields,
    automaticOutputs: [...AUTOMATIC_OUTPUT_SIGNATURES].sort((a, b) => a.id.localeCompare(b.id)),
    manualOutputs: [...MANUAL_OUTPUTS].sort((a, b) => a.id.localeCompare(b.id)),
    appConfigByBuildTarget: appConfig.record,
  };
}

function readProducers(root) {
  return Object.fromEntries(
    PRODUCER_FILES.map((file) => [file, readFileSync(path.join(root, file), 'utf8')]),
  );
}

function main(argv) {
  const check = argv.includes('--check');
  const root = process.cwd();
  const appConfig = readAppConfigTargets(root);
  const contract = buildReleaseContract(root, appConfig);
  const problems = [...checkReleaseContract(contract, readProducers(root)), ...appConfig.problems];
  const serialized = `${JSON.stringify(contract, null, 2)}\n`;
  const section = formatAppConfigTargetsMarkdown(appConfig.record);

  if (problems.length > 0) {
    console.error(`[release-contract] ${problems.length} problem(s):`);
    for (const problem of problems) console.error(`- ${problem}`);
    process.exitCode = 1;
    return;
  }

  const outputPath = path.join(root, OUTPUT_PATH);
  const registerPath = path.join(root, SECRETS_REGISTER_PATH);
  const register = readFileSync(registerPath, 'utf8');

  if (check) {
    let current = '';
    try {
      current = readFileSync(outputPath, 'utf8');
    } catch {
      current = '';
    }

    // The measured timestamp would make every run stale, so the record carries none.
    if (current !== serialized) {
      console.error(`[release-contract] ${OUTPUT_PATH} is stale. Run \`npm run release:contract\`.`);
      process.exitCode = 1;
      return;
    }

    if (!register.includes(section)) {
      console.error(
        `[release-contract] The generated section of ${SECRETS_REGISTER_PATH} is stale. Run \`npm run release:contract\`.`,
      );
      process.exitCode = 1;
      return;
    }

    console.log(
      `[release-contract] OK - ${contract.versionFields.length} version field(s) measured, ` +
        `${contract.automaticOutputs.length} automatic and ${contract.manualOutputs.length} manual output(s), ` +
        `${appConfig.record.keys.length} app-config key(s) across ${appConfig.record.targets.length} build(s).`,
    );
    return;
  }

  writeFileSync(outputPath, serialized, 'utf8');
  writeFileSync(registerPath, replaceAppConfigSection(register, section), 'utf8');
  console.log(
    `[release-contract] wrote ${OUTPUT_PATH} (${contract.versionFields.length} version fields) and the generated section of ${SECRETS_REGISTER_PATH}.`,
  );
}

if (import.meta.url === pathToFileURL(process.argv[1] ?? '').href) {
  main(process.argv.slice(2));
}
