#!/usr/bin/env node
import { existsSync, readFileSync, readdirSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import process from 'node:process';
import { fileURLToPath } from 'node:url';

/**
 * Every Greek string is Greek, or is registered as deliberately not.
 *
 * 869f135rx. EN and EL are at exact key parity - 3,169 keys each across 29
 * namespaces, zero mismatches. That is what the existing checks prove, and it is
 * not the same claim as "the Greek is Greek": an English string copied into
 * `el.json` passes key parity perfectly. `i18n-regression-check.mjs` does test
 * for Greek script, but only on the handful of public guide and help routes it
 * names, so 29 namespaces were covered by a check that looked at a few.
 *
 * This is not hypothetical here. Six Greek quotes naming the wrong button reached
 * production and were caught only when a guard was written for that specific
 * class.
 *
 * Measured 2026-09-15 on v0.4.48, across all namespaces:
 *
 *   - 636 values are BYTE-IDENTICAL in EN and EL;
 *   -   6 values differ but contain no Greek character at all;
 *   -   0 placeholder mismatches - that half is genuinely clean, and this locks
 *       it in across every namespace rather than a named few.
 *
 * Of the 636, most are the game's own vocabulary and are supposed to stay
 * English: Captain, Friend Captain, Rumble, Super Tandem, HP, ATK. That is the
 * project's rule, not an oversight - players say those words in English.
 *
 * So identical is not automatically a defect, and the check cannot simply fail on
 * it. `scripts/data/i18n-untranslated-register.json` splits them, by PHRASE
 * rather than by key, because one phrase is typically identical in several
 * namespaces and listing it once is the difference between a reviewable file and
 * a wall:
 *
 *   terms         phrases that are legitimately identical. Permanent.
 *   untranslated  phrases that are English on a Greek screen. DEBT. The list is
 *                 allowed to shrink and nothing else.
 *
 * The split was generated by a vocabulary rule and is stored as explicit phrases
 * rather than re-derived: a rule quietly admits any new phrase built from words it
 * already knows, and "Team Builder Character Box Type" is not a sentence anybody
 * should be shown. The vocabulary is recorded in the register for the next person
 * classifying a phrase, as a tool for the judgement rather than a substitute.
 *
 * Fails when:
 *
 *   A. an identical (or Greek-free) value's phrase is in neither list - something
 *      new arrived untranslated, which is the mutation this check exists for;
 *   B. a registered phrase no longer appears that way - it was translated, so its
 *      entry goes and the debt list can only shrink;
 *   C. a placeholder set differs between EN and EL, in any namespace.
 *
 * Run: npm run i18n:greek-coverage [-- --write]
 */

const HERE = path.dirname(fileURLToPath(import.meta.url));
const REPO_ROOT = path.resolve(HERE, '..');
const I18N_ROOT = path.join(REPO_ROOT, 'public', 'i18n');
const REGISTER_PATH = path.join(HERE, 'data', 'i18n-untranslated-register.json');

const GREEK_SCRIPT = /[Ͱ-Ͽἀ-῿]/u;
const LATIN_LETTER = /[A-Za-z]/u;
const PLACEHOLDER = /\{\{\s*([A-Za-z0-9_.]+)\s*\}\}/gu;
/** A separate instance: a global regex carries lastIndex, and sharing one across calls skips matches. */
const PLACEHOLDER_GLOBAL = /\{\{\s*[A-Za-z0-9_.]+\s*\}\}/gu;

export function flattenTranslations(value, prefix = '', out = {}) {
  if (value !== null && typeof value === 'object' && !Array.isArray(value)) {
    for (const [key, child] of Object.entries(value)) {
      flattenTranslations(child, prefix ? `${prefix}.${key}` : key, out);
    }
    return out;
  }
  out[prefix] = value;
  return out;
}

export function placeholdersOf(value) {
  return new Set([...String(value).matchAll(PLACEHOLDER)].map((match) => match[1]));
}

export function sameSet(left, right) {
  return left.size === right.size && [...left].every((entry) => right.has(entry));
}

/**
 * A value needs a register entry when the English has letters and the Greek shows
 * no sign of having been translated - either it is byte-identical, or it contains
 * no Greek character at all.
 */
export function classifyPair(english, greek) {
  if (typeof english !== 'string' || typeof greek !== 'string') {
    return null;
  }
  /*
   * Placeholders are removed before asking whether there is anything to
   * translate. `{{count}}` is Latin letters and is not a word - a value that is
   * only placeholders and punctuation is identical in both files because it has
   * to be, and calling that a finding would bury the real ones.
   */
  if (!LATIN_LETTER.test(english.replace(PLACEHOLDER_GLOBAL, ' '))) {
    return null;
  }
  if (GREEK_SCRIPT.test(greek)) {
    return null;
  }

  return english.trim() === greek.trim() ? 'identical' : 'no-greek';
}

/**
 * The namespaces, INCLUDING the root pair.
 *
 * `public/i18n/en.json` and `el.json` sit at the top level beside the namespace
 * directories, and a `readdirSync().filter(isDirectory)` skips them silently. The
 * first version of this check did exactly that and lost a whole namespace - which
 * is the failure this parent is about, committed inside the guard written against
 * it. `''` is that namespace and is resolved to the root.
 */
export function collectNamespaces(root = I18N_ROOT) {
  const directories = readdirSync(root, { withFileTypes: true })
    .filter((entry) => entry.isDirectory())
    .map((entry) => entry.name)
    .sort();

  return existsSync(path.join(root, 'en.json')) ? ['', ...directories] : directories;
}

export function auditTranslations(root = I18N_ROOT) {
  const findings = [];
  const placeholderMismatches = [];
  let keyCount = 0;

  for (const namespace of collectNamespaces(root)) {
    const englishPath = path.join(root, namespace, 'en.json');
    const greekPath = path.join(root, namespace, 'el.json');

    const english = flattenTranslations(JSON.parse(readFileSync(englishPath, 'utf8')));
    const greek = flattenTranslations(JSON.parse(readFileSync(greekPath, 'utf8')));

    for (const [key, value] of Object.entries(english)) {
      keyCount += 1;
      const translated = greek[key];

      if (typeof value === 'string' && typeof translated === 'string') {
        if (!sameSet(placeholdersOf(value), placeholdersOf(translated))) {
          placeholderMismatches.push({ namespace, key, english: value, greek: translated });
        }
      }

      const kind = classifyPair(value, translated);
      if (kind) {
        findings.push({ namespace, key, phrase: String(value).trim(), kind });
      }
    }
  }

  return { findings, keyCount, placeholderMismatches };
}

export function compareWithRegister(findings, register) {
  const known = new Set([...register.terms, ...register.untranslated]);
  const seen = new Set(findings.map((finding) => finding.phrase));

  const unregistered = findings.filter((finding) => !known.has(finding.phrase));
  const stale = [...known].filter((phrase) => !seen.has(phrase)).sort();

  return { stale, unregistered };
}

function parseArgs(argv) {
  const args = { write: false };
  for (const arg of argv) {
    if (arg === '--write') {
      args.write = true;
    } else {
      throw new Error(`Unknown argument: ${arg}`);
    }
  }
  return args;
}

function main() {
  const args = parseArgs(process.argv.slice(2));
  const { findings, keyCount, placeholderMismatches } = auditTranslations();
  const register = JSON.parse(readFileSync(REGISTER_PATH, 'utf8'));

  if (args.write) {
    const known = new Set([...register.terms, ...register.untranslated]);
    const additions = [...new Set(findings.map((finding) => finding.phrase))]
      .filter((phrase) => !known.has(phrase))
      .sort();
    const seen = new Set(findings.map((finding) => finding.phrase));

    register.terms = register.terms.filter((phrase) => seen.has(phrase)).sort();
    register.untranslated = [...register.untranslated.filter((phrase) => seen.has(phrase)), ...additions].sort();
    register.measuredOn = new Date().toISOString().slice(0, 10);
    writeFileSync(REGISTER_PATH, `${JSON.stringify(register, null, 2)}\n`);
    process.stdout.write(
      `[i18n] wrote register: ${register.terms.length} term(s), ${register.untranslated.length} untranslated. ` +
        `${additions.length} new phrase(s) landed in untranslated - reclassify any that are game vocabulary.\n`,
    );
    return;
  }

  const { stale, unregistered } = compareWithRegister(findings, register);
  const problems = [];

  if (placeholderMismatches.length > 0) {
    problems.push(
      `${placeholderMismatches.length} value(s) have different {{placeholders}} in EN and EL.\n` +
        `A placeholder the Greek drops renders as nothing; one it invents renders literally.\n` +
        placeholderMismatches
          .map((entry) => `  ${entry.namespace}:${entry.key}\n    en: ${entry.english}\n    el: ${entry.greek}`)
          .join('\n'),
    );
  }

  if (unregistered.length > 0) {
    const phrases = [...new Set(unregistered.map((entry) => entry.phrase))];
    problems.push(
      `${unregistered.length} Greek value(s) across ${phrases.length} phrase(s) show no sign of translation and\n` +
        `are in neither list. Translate the value, or add the phrase to "terms" in\n` +
        `scripts/data/i18n-untranslated-register.json if it is the game's own vocabulary.\n` +
        unregistered
          .slice(0, 25)
          .map((entry) => `  ${entry.namespace}:${entry.key} [${entry.kind}] ${JSON.stringify(entry.phrase)}`)
          .join('\n') +
        (unregistered.length > 25 ? `\n  ... and ${unregistered.length - 25} more` : ''),
    );
  }

  if (stale.length > 0) {
    problems.push(
      `${stale.length} registered phrase(s) no longer appear untranslated. Remove them - the\n` +
        `untranslated list is allowed to shrink and nothing else.\n` +
        stale.slice(0, 25).map((phrase) => `  ${JSON.stringify(phrase)}`).join('\n') +
        (stale.length > 25 ? `\n  ... and ${stale.length - 25} more` : ''),
    );
  }

  if (problems.length > 0) {
    for (const problem of problems) {
      process.stderr.write(`${problem}\n\n`);
    }
    process.stderr.write('FAIL i18n Greek coverage\n');
    process.exitCode = 1;
    return;
  }

  process.stdout.write(
    `OK i18n Greek coverage: ${keyCount} key(s) across ${collectNamespaces().length} namespace(s), ` +
      `0 placeholder mismatches, ${register.terms.length} registered term(s), ` +
      `${register.untranslated.length} phrase(s) of untranslated debt.\n`,
  );
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  main();
}
