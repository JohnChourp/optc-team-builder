import { readFileSync, readdirSync, statSync } from 'node:fs';
import path from 'node:path';

/**
 * 869f138qz. Which pages host each shared component, read from the imports rather than remembered.
 *
 * `src/app/shared/` holds seventeen components and utilities used across up to six hosts each -
 * **102 possible relationships**, and nothing recorded any of them. The cost is in this project's
 * own history: the shared ability modal needed six separate ClickUp tasks, one per host, to confirm
 * it rendered correctly, and `check-tag-picker-panel-scoping.mjs` exists because a shared picker's
 * panel styling leaked into one host.
 *
 * A hand-written table of 102 relationships is wrong within a month, so this reads the imports. The
 * acceptance criterion the subtask set is exactly that: **a new host of an existing shared
 * component appears without anyone updating a document.**
 *
 * The constraint beside each entry - the one thing a host must not do - is NOT generated, and is
 * deliberately `null` where it has not been established. Seventeen invented constraints would read
 * as seventeen rules and be worth less than four real ones plus an honest count of what is still
 * unknown.
 */

/** Directories whose exports are functions rather than components. */
function classify(exports, inputs, outputs) {
  if (exports.length === 0) {
    return 'utility';
  }

  return inputs.length || outputs.length ? 'component' : 'component-without-bindings';
}

function listFiles(directory) {
  return readdirSync(directory, { withFileTypes: true }).flatMap((entry) => {
    const entryPath = path.join(directory, entry.name);

    if (entry.isDirectory()) {
      return listFiles(entryPath);
    }

    return entry.isFile() ? [entryPath] : [];
  });
}

/** `@Input()`/`@Output()` names, and the classes a directory exports. */
export function readSharedComponentApi(directory) {
  const exports = [];
  const inputs = [];
  const outputs = [];

  for (const filePath of listFiles(directory)) {
    if (!filePath.endsWith('.ts') || filePath.includes('.spec.')) {
      continue;
    }

    const source = readFileSync(filePath, 'utf8');

    exports.push(...[...source.matchAll(/export class (\w+)/gu)].map(([, name]) => name));
    inputs.push(
      ...[...source.matchAll(/@Input\([^)]*\)\s*(?:public\s+)?(?:readonly\s+)?(\w+)/gu)].map(
        ([, name]) => name,
      ),
    );
    outputs.push(
      ...[...source.matchAll(/@Output\([^)]*\)\s*(?:public\s+)?(?:readonly\s+)?(\w+)/gu)].map(
        ([, name]) => name,
      ),
    );
  }

  return {
    exports: [...new Set(exports)].sort(),
    inputs: [...new Set(inputs)].sort(),
    outputs: [...new Set(outputs)].sort(),
  };
}

/**
 * Every non-spec file outside `shared/<id>/` that imports from it.
 *
 * Matched on the directory segment rather than on a relative prefix, because a host two levels up
 * writes `../../shared/ship-picker/...` and a sibling inside `shared/` writes `../ship-picker/...` -
 * and the second is exactly how 869f138q3 undercounted the `a11y` consumers by more than half.
 */
export function findSharedComponentHosts({ appRoot, componentId }) {
  const marker = `/${componentId}/`;
  const ownDirectory = path.join('src', 'app', 'shared', componentId);
  const hosts = [];

  for (const filePath of listFiles(path.join(appRoot, 'src', 'app'))) {
    const relativePath = path.relative(appRoot, filePath);

    if (
      relativePath.startsWith(ownDirectory) ||
      relativePath.includes('.spec.') ||
      !(relativePath.endsWith('.ts') || relativePath.endsWith('.html'))
    ) {
      continue;
    }

    const source = readFileSync(filePath, 'utf8');
    const imports = [...source.matchAll(/from '([^']+)'/gu)].map(([, specifier]) => specifier);

    if (imports.some((specifier) => specifier.includes(marker))) {
      hosts.push(relativePath.replace(/\\/gu, '/'));
    }
  }

  return hosts.sort();
}

export function buildSharedComponentMap({ appRoot, constraints }) {
  const sharedRoot = path.join(appRoot, 'src', 'app', 'shared');
  const componentIds = readdirSync(sharedRoot, { withFileTypes: true })
    .filter((entry) => entry.isDirectory())
    .map((entry) => entry.name)
    .sort();

  const components = componentIds.map((componentId) => {
    const api = readSharedComponentApi(path.join(sharedRoot, componentId));
    const hosts = findSharedComponentHosts({ appRoot, componentId });

    return {
      id: componentId,
      kind: classify(api.exports, api.inputs, api.outputs),
      exports: api.exports,
      inputs: api.inputs,
      outputs: api.outputs,
      hostCount: hosts.length,
      hosts,
      hostConstraint: Object.hasOwn(constraints, componentId) ? constraints[componentId] : undefined,
    };
  });

  return {
    note: 'Generated by scripts/generate-shared-component-map.mjs from the imports. Do not edit by hand. `hostConstraint` is the one thing a host must not do, and is null where none has been established rather than invented.',
    componentCount: components.length,
    relationshipCount: components.reduce((total, component) => total + component.hostCount, 0),
    constraintsEstablished: components.filter((component) => component.hostConstraint).length,
    components,
  };
}

/** A component with no constraint entry at all, or an entry for a component that is gone. */
export function findConstraintGaps({ componentIds, constraints }) {
  const declared = new Set(Object.keys(constraints));
  const present = new Set(componentIds);

  return [
    ...componentIds
      .filter((id) => !declared.has(id))
      .map((id) => ({
        kind: 'component-without-constraint-entry',
        componentId: id,
        detail:
          'has no entry in HOST_CONSTRAINTS - add one, or add it with null to record that none is established yet',
      })),
    ...[...declared]
      .filter((id) => !present.has(id))
      .sort()
      .map((id) => ({
        kind: 'constraint-for-missing-component',
        componentId: id,
        detail: 'has a HOST_CONSTRAINTS entry but no directory under src/app/shared',
      })),
  ];
}
