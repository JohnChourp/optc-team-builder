#!/usr/bin/env node
import { readFileSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import process from 'node:process';
import { fileURLToPath } from 'node:url';

import { readWorkerProtocol } from './lib/worker-protocol.mjs';

/**
 * 869f138qx. Writes `docs/worker-protocols.json` from the three workers' models.
 *
 * Why it is read from the models rather than written, and how direction is derived rather than
 * guessed, is in `scripts/lib/worker-protocol.mjs`.
 *
 * Run: npm run workers:protocols           (write)
 *      npm run workers:protocols -- --check (fail when the file is stale or a kind is undocumented)
 */

const APP_ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const SERVICES = path.join(APP_ROOT, 'src/app/core/services');
const OUTPUT_PATH = path.join(APP_ROOT, 'docs/worker-protocols.json');

const WORKERS = Object.freeze([
  {
    id: 'auto-team-builder',
    modelsPath: path.join(SERVICES, 'auto-team-builder.worker.models.ts'),
    requestUnion: 'AutoTeamBuilderWorkerRequest',
    responseUnion: 'AutoTeamBuilderWorkerResponse',
  },
  {
    id: 'auto-team-builder-rumble',
    modelsPath: path.join(SERVICES, 'auto-team-builder-rumble.worker.models.ts'),
    requestUnion: 'AutoTeamBuilderRumbleWorkerRequest',
    responseUnion: 'AutoTeamBuilderRumbleWorkerResponse',
  },
  {
    id: 'captain-coverage-filter',
    modelsPath: path.join(SERVICES, 'captain-coverage-filter.worker.models.ts'),
    requestUnion: 'CaptainCoverageFilterWorkerRequest',
    responseUnion: 'CaptainCoverageFilterWorkerResponse',
  },
]);

export function buildWorkerProtocolDocument() {
  const workers = WORKERS.map((worker) =>
    readWorkerProtocol({ ...worker, modelsPath: worker.modelsPath }),
  ).map((worker) => ({
    ...worker,
    modelsPath: path.relative(APP_ROOT, worker.modelsPath).replace(/\\/gu, '/'),
  }));

  return {
    note: 'Generated by scripts/generate-worker-protocols.mjs from the workers\' own models. Do not edit by hand. Direction comes from the union name: a …WorkerRequest goes page to worker, a …WorkerResponse goes worker to page.',
    workerCount: workers.length,
    messageCount: workers.reduce((total, worker) => total + worker.messages.length, 0),
    /*
     * The point of putting all three side by side. They correlate a reply to its request with
     * DIFFERENT fields - and that is exactly the kind of divergence nobody could see while each
     * protocol lived only in its own file.
     */
    correlationFieldsByWorker: Object.fromEntries(
      workers.map((worker) => [worker.id, worker.correlationFields]),
    ),
    workers,
  };
}

function serialize(document) {
  return `${JSON.stringify(document, null, 2)}\n`;
}

function main() {
  const check = process.argv.includes('--check');
  const document = buildWorkerProtocolDocument();
  const undocumented = document.workers.flatMap((worker) =>
    worker.undocumented.map((entry) => ({ worker: worker.id, ...entry })),
  );

  if (undocumented.length) {
    console.error('[worker-protocols] a message has no readable kind, so it has no direction:');

    for (const entry of undocumented) {
      console.error(`- ${entry.worker} ${entry.union}: ${entry.member}`);
    }

    process.exitCode = 1;

    return;
  }

  const next = serialize(document);

  if (!check) {
    writeFileSync(OUTPUT_PATH, next, 'utf8');
    console.log(
      `[worker-protocols] wrote docs/worker-protocols.json (${document.workerCount} workers, ${document.messageCount} messages).`,
    );

    return;
  }

  let current = '';

  try {
    current = readFileSync(OUTPUT_PATH, 'utf8');
  } catch {
    current = '';
  }

  if (current === next) {
    console.log(
      `[worker-protocols] OK - ${document.workerCount} workers, ${document.messageCount} messages, every kind with a direction.`,
    );

    return;
  }

  console.error(
    '[worker-protocols] docs/worker-protocols.json does not match the models. It is GENERATED - run `npm run workers:protocols`.',
  );
  process.exitCode = 1;
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  main();
}

export { WORKERS, serialize };
