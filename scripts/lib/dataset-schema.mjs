/**
 * 869f138qt. The tables the app queries, read out of the seed rather than described by hand.
 *
 * `docs/data-schemas.md` documents the shapes the application reasons about - character records,
 * saved teams, enemy definitions. Nothing documented the layer beneath: what is actually in the
 * database. That absence is why a question like "is the catalogue query a table scan?" could not be
 * answered by reading, and had to be measured instead
 * ([869f138q1](https://app.clickup.com/t/90121749478/869f138q1)).
 *
 * The task said four tables and 9,303 inserts. Measured 2026-09-17: **six tables and 13,850
 * inserts**, which is the whole argument for generating this. A hand-written schema is wrong the
 * first time a column changes and nobody finds out.
 *
 * Two things are called out per column because they are where reading the schema stops being
 * enough:
 *
 * - **JSON-bearing columns.** `region_json`, `assets_json`, `detail_json` and the rest hold a
 *   serialized object in a TEXT column, so the type says TEXT and the content has a shape SQLite
 *   knows nothing about. They are detected by parsing a real value, not by the `_json` suffix -
 *   a column could be named anything, and a column named `_json` could hold something else.
 * - **Indexes.** There are none beyond the implicit rowid of an `INTEGER PRIMARY KEY`, and stating
 *   that is more useful than leaving a reader to infer it from silence.
 */

/** Columns whose every sampled value parses as an object or array. */
const JSON_SAMPLE_LIMIT = 20;

function looksLikeJson(value) {
  if (typeof value !== 'string') {
    return false;
  }

  const trimmed = value.trim();

  if (!trimmed.startsWith('{') && !trimmed.startsWith('[')) {
    return false;
  }

  try {
    const parsed = JSON.parse(trimmed);

    return typeof parsed === 'object' && parsed !== null;
  } catch {
    return false;
  }
}

function queryAll(database, sql) {
  const result = database.exec(sql);

  if (!result.length) {
    return [];
  }

  const [{ columns, values }] = result;

  return values.map((row) => Object.fromEntries(columns.map((name, index) => [name, row[index]])));
}

/**
 * Whether every non-null sample in `column` is JSON.
 *
 * Every sample, not any: one JSON-looking value in a free-text column would otherwise label the
 * column as structured and send a reader looking for a shape that is not there.
 */
export function detectJsonColumn(database, table, column) {
  const rows = queryAll(
    database,
    `SELECT "${column}" AS value FROM "${table}" WHERE "${column}" IS NOT NULL LIMIT ${JSON_SAMPLE_LIMIT}`,
  );

  return rows.length > 0 && rows.every((row) => looksLikeJson(row.value));
}

/**
 * The schema as the database reports it.
 *
 * `sqlite_master` rather than the seed's text: the text is what was written, and this is what
 * SQLite made of it, which is the thing the app queries.
 */
export function readDatasetSchema(database) {
  const tables = queryAll(
    database,
    "SELECT name FROM sqlite_master WHERE type = 'table' AND name NOT LIKE 'sqlite_%' ORDER BY name",
  ).map((row) => row.name);

  return {
    tableCount: tables.length,
    tables: tables.map((table) => {
      const columns = queryAll(database, `PRAGMA table_info("${table}")`);
      const [{ rowCount }] = queryAll(database, `SELECT COUNT(*) AS rowCount FROM "${table}"`);
      const indexes = queryAll(database, `PRAGMA index_list("${table}")`).map((index) => ({
        name: index.name,
        unique: index.unique === 1,
        origin: index.origin,
      }));

      return {
        name: table,
        rowCount,
        columns: columns.map((column) => ({
          name: column.name,
          type: column.type,
          notNull: column.notnull === 1,
          primaryKey: column.pk > 0,
          defaultValue: column.dflt_value ?? null,
          holdsJson: detectJsonColumn(database, table, column.name),
        })),
        indexes,
      };
    }),
  };
}

/** The file, with the note that says not to edit it. */
export function buildDatasetSchemaDocument({ schema, generatedAt, statementCounts }) {
  return {
    generatedAt,
    note: 'Generated by scripts/generate-dataset-schema.mjs from public/assets/data/optc-seed.sql. Do not edit by hand. This is the DATABASE layer - the tables the app queries. docs/data-schemas.md documents the application shapes those rows become.',
    ...statementCounts,
    ...schema,
  };
}

/** `CREATE TABLE`, `INSERT INTO` and `CREATE INDEX` counts, straight off the seed text. */
export function countSeedStatements(seedText) {
  const count = (pattern) => (seedText.match(pattern) ?? []).length;

  return {
    createTableStatements: count(/CREATE TABLE/gu),
    insertStatements: count(/INSERT INTO/gu),
    createIndexStatements: count(/CREATE INDEX/gu),
  };
}
