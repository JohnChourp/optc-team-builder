import { readFileSync, readdirSync, statSync } from 'node:fs';
import path from 'node:path';

/**
 * 869f138qw. What an offline image pack is, declared as data instead of implied by a folder.
 *
 * 869f138pr established what the packs DO: 161.6 MB that ship (189 MB is `du`'s DISK USAGE, not the
 * packs' size - see `offline-pack-status.utils.ts`), never prefetched, fetched one
 * image at a time as a reader browses, and are cached by the service worker's `runtime-media` group.
 * What no file said is the contract - which pack holds what, what it costs, where it sits in the
 * precedence chain that resolves a character's picture, and what happens when it has no entry.
 *
 * Two things are measured here rather than taken from the manifest, and the difference between them
 * is the point:
 *
 * - **the manifest CLAIMS a size.** `import-optc-data.mjs` writes `totalBytes: cached?.totalBytes`,
 *   which is what the pack weighed when it was cached, not what is on disk now.
 * - **this measures the files.** Measured 2026-09-17, the two claims disagree with the disk by
 *   **+919** and **-563** bytes. Nothing had ever compared them, and the Settings card added by
 *   869f138pr shows the manifest's claim.
 *
 * So the file count is the invariant worth failing on - it is exact, and a pack that gained or lost
 * an image is a real event - while the byte drift is recorded with its cause rather than papered
 * over with a tolerance nobody chose.
 */

/**
 * OS artifacts that must never reach a committed, generated document.
 *
 * `.DS_Store` is gitignored and exists only on the machine that opened the folder in Finder, so
 * recording it would make this file differ between a developer's disk and CI - and the `--check`
 * would fail there for a reason that has nothing to do with the packs. Found before it shipped by
 * asking `git check-ignore` what was in the directory rather than trusting the listing.
 */
export const IGNORED_LOCAL_FILES = Object.freeze(['.DS_Store', 'Thumbs.db', 'desktop.ini']);

export function measurePackDirectory(directory) {
  let fileCount = 0;
  let totalBytes = 0;
  const markers = [];

  const walk = (current) => {
    for (const entry of readdirSync(current, { withFileTypes: true })) {
      const entryPath = path.join(current, entry.name);

      if (entry.isDirectory()) {
        walk(entryPath);
        continue;
      }

      if (!entry.isFile()) {
        continue;
      }

      if (IGNORED_LOCAL_FILES.includes(entry.name)) {
        continue;
      }

      if (entry.name.startsWith('.')) {
        markers.push(entry.name);
        continue;
      }

      fileCount += 1;
      totalBytes += statSync(entryPath).size;
    }
  };

  walk(directory);

  return { fileCount, totalBytes, markers: [...new Set(markers)].sort() };
}

/**
 * Where a pack sits in the chain that decides a character's picture.
 *
 * Read from `optc-repository.service.ts`'s `resolveImageUrl`, whose order is: a local exact image
 * (detail pages only), the local thumbnail, the local exact image again, then the Global pack, then
 * the Japan pack, then the placeholder. The reader's own override outranks all of it and is applied
 * afterwards, in `character-overrides.utils.ts`.
 *
 * Hard-coded rather than parsed: parsing a chain of `if` statements to produce a number would be a
 * second implementation of the chain, and it would agree with the first right up until it did not.
 * The spec asserts the order against the real source instead.
 */
export const PACK_PRECEDENCE = Object.freeze({
  'thumbnails-glo': 4,
  'thumbnails-jap': 5,
  'ship-thumbnails': null,
});

export function buildOfflinePackContract({ packsRoot, manifest, cacheConfig }) {
  const directories = readdirSync(packsRoot, { withFileTypes: true })
    .filter((entry) => entry.isDirectory())
    .map((entry) => entry.name)
    .sort();
  const claimed = new Map((manifest.packs ?? []).map((pack) => [pack.id, pack]));

  const packs = directories.map((id) => {
    const measured = measurePackDirectory(path.join(packsRoot, id));
    const claim = claimed.get(id);

    return {
      id,
      manifestKey: claim?.key ?? null,
      label: claim?.label ?? null,
      localBasePath: `assets/offline-packs/${id}`,
      measuredFileCount: measured.fileCount,
      measuredBytes: measured.totalBytes,
      manifestFileCount: claim?.fileCount ?? null,
      manifestBytes: claim?.totalBytes ?? null,
      byteDrift: claim ? measured.totalBytes - claim.totalBytes : null,
      markerFiles: measured.markers,
      precedenceRank: Object.hasOwn(PACK_PRECEDENCE, id) ? PACK_PRECEDENCE[id] : undefined,
    };
  });

  return {
    note: "Generated by scripts/generate-offline-pack-contract.mjs from the pack directories and the dataset manifest. Do not edit by hand. `measured*` is what is on disk; `manifest*` is what the manifest claims, which import-optc-data.mjs takes from a cache record rather than from the files.",
    packCount: packs.length,
    /* What the service worker will hold, from ngsw-config.json - the ceiling on offline usefulness. */
    runtimeCache: cacheConfig,
    precedence: [
      'Reader override (character-overrides.utils.ts) - outranks everything below',
      'Local exact image, on detail pages only',
      'Local thumbnail',
      'Local exact image, everywhere else',
      'Global thumbnails pack (thumbnails-glo)',
      'Japan thumbnails pack (thumbnails-jap)',
      'Placeholder - reached only when no path was recorded, never when a path fails to load',
    ],
    packs,
  };
}

/** A pack on disk with no manifest entry, a manifest entry with no pack, or a count that moved. */
export function findPackContractFailures(contract) {
  return contract.packs.flatMap((pack) => {
    if (pack.manifestKey === null) {
      return [
        {
          kind: 'pack-without-manifest-entry',
          packId: pack.id,
          detail: 'ships under public/assets/offline-packs but the dataset manifest never mentions it',
        },
      ];
    }

    if (pack.measuredFileCount !== pack.manifestFileCount) {
      return [
        {
          kind: 'pack-file-count-drift',
          packId: pack.id,
          detail: `holds ${pack.measuredFileCount} files, the manifest claims ${pack.manifestFileCount}`,
        },
      ];
    }

    return [];
  });
}
