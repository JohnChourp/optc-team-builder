#!/usr/bin/env node
/**
 * 869f13d8b. Writes which environment each suite meets and what it may assume, and checks it.
 *
 * Derived, not restated: the projects come from `vitest.config.mjs` itself, the suites from
 * `SCRIPT_SUITES`, and the gate membership from `package.json`. A second hand-written copy
 * of the environment map is precisely the thing that drifts.
 *
 * `--check` compares instead of writing. It deliberately carries NO DOM-global check - see
 * `lib/suite-environments.mjs` for the measurement that refused one.
 *
 * Run: npm run test:suite-environments
 */
import { readFileSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import process from 'node:process';
import { pathToFileURL } from 'node:url';

import { SCRIPT_SUITES } from './ci-check-routing.mjs';
import {
  ENVIRONMENTS,
  GATED_PERF_SCRIPTS,
  checkSuiteEnvironments,
  environmentForSpec,
} from './lib/suite-environments.mjs';

const OUTPUT_PATH = 'docs/suite-environments.json';
export const SCHEMA_VERSION = 1;

/** Reads the projects out of the real config rather than describing them again. */
export async function readVitestProjects(root = process.cwd()) {
  const configPath = path.join(root, 'vitest.config.mjs');
  const config = (await import(pathToFileURL(configPath).href)).default;

  return (config.test?.projects ?? []).map((project) => ({
    name: project.test.name,
    environment: project.test.environment,
    include: project.test.include,
    setupFiles: project.test.setupFiles ?? [],
  }));
}

export async function buildSuiteEnvironments(root = process.cwd()) {
  const projects = await readVitestProjects(root);
  const pkg = JSON.parse(readFileSync(path.join(root, 'package.json'), 'utf8'));
  const suites = [];

  for (const [id, suite] of Object.entries(SCRIPT_SUITES)) {
    const command = suite.command;
    const resolved = command.startsWith('npm run ') ? pkg.scripts[command.slice('npm run '.length)] ?? '' : command;

    // A suite runs `ng test` (the angular lane's runner) or plain vitest over named specs.
    const usesNgTest = /\bng test\b/u.test(resolved);
    const specPaths = [...resolved.matchAll(/(?:^|\s)((?:scripts|src|e2e|server)\/\S+?\.spec\.(?:ts|mjs))/gu)].map((m) => m[1]);
    const environments = new Set(
      usesNgTest ? ['jsdom'] : specPaths.map((spec) => environmentForSpec(spec, projects)).filter(Boolean),
    );

    suites.push({
      id,
      label: suite.label,
      command,
      environment: environments.size === 1 ? [...environments][0] : environments.size === 0 ? 'node' : 'mixed',
      environments: [...environments].sort(),
      specCount: specPaths.length,
    });
  }

  // Playwright and the gated harnesses are suites too, and are the ones a reader forgets.
  for (const browser of ['chromium', 'firefox', 'webkit']) {
    suites.push({
      id: `e2e-${browser}`,
      label: `Cross-browser e2e (${browser})`,
      command: `npm run test:e2e:${browser}`,
      environment: 'browser',
      environments: ['browser'],
      specCount: null,
    });
  }

  for (const script of GATED_PERF_SCRIPTS) {
    suites.push({
      id: script,
      label: `Performance harness (${script})`,
      command: `npm run ${script}`,
      environment: 'gated-chromium',
      environments: ['gated-chromium'],
      specCount: null,
    });
  }

  return {
    schemaVersion: SCHEMA_VERSION,
    note:
      'Generated by scripts/generate-suite-environments.mjs from vitest.config.mjs, SCRIPT_SUITES and package.json. Do not edit by hand.',
    environments: ENVIRONMENTS,
    projects,
    suites: suites.sort((a, b) => a.id.localeCompare(b.id)),
  };
}

async function main(argv) {
  const check = argv.includes('--check');
  const root = process.cwd();
  const record = await buildSuiteEnvironments(root);
  const problems = checkSuiteEnvironments(record);

  if (problems.length > 0) {
    console.error(`[suite-environments] ${problems.length} problem(s):`);
    for (const problem of problems) console.error(`- ${problem}`);
    process.exitCode = 1;
    return;
  }

  const serialized = `${JSON.stringify(record, null, 2)}\n`;
  const outputPath = path.join(root, OUTPUT_PATH);

  if (check) {
    let current = '';
    try {
      current = readFileSync(outputPath, 'utf8');
    } catch {
      current = '';
    }

    if (current !== serialized) {
      console.error(`[suite-environments] ${OUTPUT_PATH} is stale. Run \`npm run test:suite-environments\` after \`node ./scripts/generate-suite-environments.mjs\`.`);
      process.exitCode = 1;
      return;
    }

    const counts = record.suites.reduce((acc, suite) => {
      acc[suite.environment] = (acc[suite.environment] ?? 0) + 1;
      return acc;
    }, {});

    console.log(
      `[suite-environments] OK - ${record.suites.length} suite(s): ` +
        Object.entries(counts)
          .sort()
          .map(([env, n]) => `${n} ${env}`)
          .join(', '),
    );
    return;
  }

  writeFileSync(outputPath, serialized, 'utf8');
  console.log(`[suite-environments] wrote ${OUTPUT_PATH} (${record.suites.length} suites).`);
}

if (import.meta.url === pathToFileURL(process.argv[1] ?? '').href) {
  void main(process.argv.slice(2));
}
