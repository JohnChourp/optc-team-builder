#!/usr/bin/env node
/**
 * 869f127dr. The dataset only moves at RELEASE time: `optc-release` commits the regenerated
 * `optc-seed.sql`, `optc-preview.json` and friends straight to `main`. So a branch that changes the
 * importer passes every local run against the OLD data and goes red on `main` after the release
 * regenerates it. Recorded after v0.4.10.
 *
 * The audit picked Option 1 - stop pinning dataset-derived values and resolve them instead -
 * because Option 2 costs a full dataset regeneration per pull request in a repository that runs no
 * CI on pull requests at all.
 *
 * Measured before building this: `auto-team-builder.service.spec.ts` pins **357**
 * `loadGeneratedCharacterRecord(<id>)` call sites and **550** test titles of the shape
 * `#<id> <Name>` - and asserts a character name **zero** times. That is two different defects
 * wearing one coat:
 *
 *  1. A pinned ID that the release removes makes the spec THROW, on `main`, after the release. Red,
 *     but at the wrong time and with an opaque message.
 *  2. A pinned NAME in a title that upstream renames fails nothing at all. 550 titles quietly
 *     describe characters the dataset no longer calls that. A silent lie is worse than a red lane,
 *     because nothing ever brings it up.
 *
 * This resolves both against the shipped dataset rather than trusting the literal. It is the
 * cheapest thing that removes the class: the pins stop being a second, unverified copy of the
 * dataset, so regenerating the dataset can no longer make them wrong without saying so.
 */
import { readFileSync, readdirSync, statSync } from 'node:fs';
import path from 'node:path';
import process from 'node:process';

const SEED_PATH = 'public/assets/data/optc-seed.sql';
const PREVIEW_PATH = 'public/assets/data/optc-preview.json';

/** `loadGeneratedCharacterRecord(123)` - the call that reads a character out of the shipped data. */
const PINNED_RECORD_PATTERN = /loadGeneratedCharacterRecord\(\s*(\d+)\s*\)/gu;

/** `#123 Some Character Name` inside a test title, up to the next quote or a trailing clause. */
const TITLE_PIN_PATTERN = /#(\d+)\s+([^'"`]+?)(?=\s+(?:as|with|for|when|and|keeps|stays|is|in|on|to|from|at)\b|['"`])/gu;

export function listSpecFiles(root) {
  const files = [];

  const walk = (dir) => {
    let entries;

    try {
      entries = readdirSync(dir);
    } catch {
      return;
    }

    for (const entry of entries) {
      const full = path.join(dir, entry);
      let info;

      try {
        info = statSync(full);
      } catch {
        continue;
      }

      if (info.isDirectory()) {
        if (entry !== 'node_modules') {
          walk(full);
        }
      } else if (entry.endsWith('.spec.ts')) {
        files.push(full);
      }
    }
  };

  walk(root);

  return files.sort();
}

/**
 * Character id to name, from the shipped seed. Read with a narrow regular expression rather than a
 * SQL parser: the file is 25 MB and generated by one writer, so its shape is known, and a parser
 * here would be a second thing to keep in step with the importer.
 */
export function readShippedCharacterNames(appRoot) {
  const namesById = new Map();
  const seedFile = path.join(appRoot, SEED_PATH);
  let sql;

  try {
    sql = readFileSync(seedFile, 'utf8');
  } catch {
    return namesById;
  }

  const insertPattern = /INSERT INTO characters \([^)]*\) VALUES \(\s*(\d+),\s*'((?:[^']|'')*)'/gu;
  let match;

  while ((match = insertPattern.exec(sql)) !== null) {
    namesById.set(Number(match[1]), match[2].replace(/''/gu, "'"));
  }

  try {
    const preview = JSON.parse(readFileSync(path.join(appRoot, PREVIEW_PATH), 'utf8'));

    for (const character of preview?.characters ?? []) {
      if (typeof character?.id === 'number' && typeof character?.name === 'string') {
        namesById.set(character.id, character.name);
      }
    }
  } catch {
    // The preview is a subset of the seed and is optional here; an unreadable one costs coverage,
    // never correctness, because every id it carries is in the seed too.
  }

  return namesById;
}

export function collectPins(source) {
  const recordIds = new Set();
  const titlePins = [];
  let match;

  PINNED_RECORD_PATTERN.lastIndex = 0;

  while ((match = PINNED_RECORD_PATTERN.exec(source)) !== null) {
    recordIds.add(Number(match[1]));
  }

  for (const line of source.split(/\r?\n/u)) {
    if (!/\b(it|test|describe)\s*\(/u.test(line)) {
      continue;
    }

    TITLE_PIN_PATTERN.lastIndex = 0;

    while ((match = TITLE_PIN_PATTERN.exec(line)) !== null) {
      const name = match[2].trim();

      // A bare `#12` with no name after it pins nothing, and a number is not a name.
      if (name && !/^\d+$/u.test(name)) {
        titlePins.push({ id: Number(match[1]), name });
      }
    }
  }

  return { recordIds: [...recordIds].sort((left, right) => left - right), titlePins };
}

export function inspectDatasetSpecPins({ appRoot = process.cwd(), sourceRoot = 'src' } = {}) {
  const namesById = readShippedCharacterNames(appRoot);
  const findings = [];
  let checkedFiles = 0;
  let checkedPins = 0;

  if (namesById.size === 0) {
    return {
      checkedFiles: 0,
      checkedPins: 0,
      datasetCharacters: 0,
      findings: [
        {
          kind: 'missing-dataset',
          detail: `${SEED_PATH} could not be read, so no pin can be resolved. Run npm run data:import:all first.`,
        },
      ],
      ok: false,
    };
  }

  for (const file of listSpecFiles(path.join(appRoot, sourceRoot))) {
    const source = readFileSync(file, 'utf8');

    if (!source.includes('loadGeneratedCharacterRecord') && !source.includes('#')) {
      continue;
    }

    const relativePath = path.relative(appRoot, file).split(path.sep).join('/');
    const { recordIds, titlePins } = collectPins(source);

    if (recordIds.length === 0 && titlePins.length === 0) {
      continue;
    }

    checkedFiles += 1;

    for (const id of recordIds) {
      checkedPins += 1;

      if (!namesById.has(id)) {
        findings.push({
          kind: 'missing-character',
          file: relativePath,
          id,
          detail: `loadGeneratedCharacterRecord(${id}) names a character the shipped dataset no longer has.`,
        });
      }
    }

    /*
     * Titles are only checked for ids the file also loads. A `#4` in prose about something else -
     * a pull request number, a slot - is not a dataset pin, and treating it as one would make this
     * guard the thing that fails for a reason nobody can act on.
     */
    const loadedIds = new Set(recordIds);

    for (const pin of titlePins) {
      if (!loadedIds.has(pin.id)) {
        continue;
      }

      checkedPins += 1;

      const actual = namesById.get(pin.id);

      if (actual === undefined) {
        continue;
      }

      if (!actual.startsWith(pin.name)) {
        findings.push({
          kind: 'stale-name',
          file: relativePath,
          id: pin.id,
          expected: actual,
          actual: pin.name,
          detail: `A title calls #${pin.id} "${pin.name}"; the shipped dataset calls it "${actual}".`,
        });
      }
    }
  }

  return { checkedFiles, checkedPins, datasetCharacters: namesById.size, findings, ok: findings.length === 0 };
}

export function formatDatasetSpecPinResult(result) {
  if (result.ok) {
    return `[dataset:spec-pins] resolved ${result.checkedPins} pin(s) across ${result.checkedFiles} spec file(s) against ${result.datasetCharacters} shipped characters.`;
  }

  const lines = [`[dataset:spec-pins] found ${result.findings.length} pin(s) the shipped dataset does not support:`];

  for (const finding of result.findings) {
    lines.push(finding.file ? `- ${finding.file}: ${finding.detail}` : `- ${finding.detail}`);
  }

  lines.push(
    '[dataset:spec-pins] The dataset only moves at release, so a pin that drifts goes red on main',
    '[dataset:spec-pins] rather than on the branch that changed the importer. Resolve the value from',
    '[dataset:spec-pins] the dataset instead of repeating it, or update the pin in the same change.',
  );

  return lines.join('\n');
}

function parseArgs(argv) {
  const options = { appRoot: process.cwd(), sourceRoot: 'src' };

  for (let index = 0; index < argv.length; index += 1) {
    if (argv[index] === '--app-root') {
      options.appRoot = argv[index + 1] ?? options.appRoot;
      index += 1;
    } else if (argv[index] === '--source-root') {
      options.sourceRoot = argv[index + 1] ?? options.sourceRoot;
      index += 1;
    }
  }

  return options;
}

if (process.argv[1] && import.meta.url === new URL(`file://${process.argv[1]}`).href) {
  const result = inspectDatasetSpecPins(parseArgs(process.argv.slice(2)));

  console.log(formatDatasetSpecPinResult(result));

  if (!result.ok) {
    process.exit(1);
  }
}
