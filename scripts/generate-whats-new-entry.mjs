#!/usr/bin/env node
/**
 * Writes the What's New entry a release would otherwise ship without.
 *
 * The nightly `check-optc-db-release` -> `release-android` chain bumps the
 * version with no human in the loop, and nothing in it wrote an entry. Because
 * `check-whats-new.mjs` fails the moment package.json moves ahead of the entry
 * list, every data-only automatic release left `main` red on the `whats-new`
 * lane until somebody noticed and wrote one by hand. That happened on
 * 2026-09-04 (v0.2.2, one new character, nobody told) and is ClickUp 869evymcv.
 *
 * This never overwrites a human entry: if the version is already described it
 * exits having done nothing, so a person writing a proper release note always
 * wins. It only fills the gap the automated chain leaves behind.
 *
 * What it can say is deliberately narrow, because a data release only ever does
 * one thing a player notices: characters appear. It reads them out of the seed
 * SQL that `data:import:all` has already regenerated by the time the release
 * script calls this.
 */

import { execFileSync } from 'node:child_process';
import { existsSync, readFileSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import process from 'node:process';

export const WHATS_NEW_DATA_PATH = 'src/app/core/data/whats-new.data.ts';
/**
 * The roster lives in the seed, not in `optc-preview.json` - that file is a
 * 24-character sample for the landing page, and using it here reported "no new
 * characters" for the very release this script exists because of.
 */
export const SEED_DATA_PATH = 'public/assets/data/optc-seed.sql';

/** How many characters we name before falling back to "and N more". */
export const NAMED_CHARACTER_LIMIT = 6;

export function hasEntryFor(source, version) {
  return new RegExp(`version:\\s*'${version.replace(/\./gu, '\\.')}'`, 'u').test(source);
}

/**
 * Characters present in `next` and absent from `previous`, in dataset order.
 * Removals are counted but never announced - a character leaving the upstream
 * dataset is a correction, not something a player did anything to lose.
 */
export function diffCharacters(previous, next) {
  const previousIds = new Set((previous ?? []).map((character) => character.id));
  const nextIds = new Set((next ?? []).map((character) => character.id));

  return {
    added: (next ?? []).filter((character) => !previousIds.has(character.id)),
    removedCount: (previous ?? []).filter((character) => !nextIds.has(character.id)).length,
    previousCount: previousIds.size,
    nextCount: nextIds.size,
  };
}

function describeCharacter(character) {
  const classes = [character.primaryClass, character.secondaryClass].filter(Boolean).join('/');
  const parts = [character.type, classes].filter(Boolean).join(' ');
  const stars = Number.isFinite(character.stars) ? `${character.stars}-star ` : '';

  return parts ? `${character.name} (${stars}${parts})` : character.name;
}

function describeCharacterEl(character) {
  const classes = [character.primaryClass, character.secondaryClass].filter(Boolean).join('/');
  const parts = [character.type, classes].filter(Boolean).join(' ');
  const stars = Number.isFinite(character.stars) ? `${character.stars} αστέρων ` : '';

  return parts ? `${character.name} (${stars}${parts})` : character.name;
}

function joinNames(names, conjunction) {
  if (names.length <= 1) {
    return names.join('');
  }

  return `${names.slice(0, -1).join(', ')} ${conjunction} ${names[names.length - 1]}`;
}

/**
 * The entry itself. A data release that added nobody is honest about that and
 * sets `userVisible: false` with all three lists empty, which is exactly what
 * `check-whats-new.mjs` requires of a quiet release.
 */
export function buildEntry({ version, date, added }) {
  const count = added.length;

  if (count === 0) {
    return {
      version,
      date,
      userVisible: false,
      headline: {
        en: 'Fresh game data, nothing new to see',
        el: 'Φρέσκα δεδομένα, τίποτα νέο να δεις',
      },
      summaryEn:
        'This release only refreshed the game data behind the app. No characters were added and nothing changed on any screen, so there is nothing here for you to look at - it is listed so the version numbers do not skip.',
      summaryEl:
        'Αυτή η έκδοση απλώς ανανέωσε τα δεδομένα του παιχνιδιού πίσω από την εφαρμογή. Δεν προστέθηκε κανένας χαρακτήρας και δεν άλλαξε τίποτα σε καμία οθόνη, οπότε δεν έχεις κάτι να δεις - μπαίνει στη λίστα μόνο για να μη λείπει αριθμός έκδοσης.',
      added: [],
      improved: [],
      fixed: [],
    };
  }

  const named = added.slice(0, NAMED_CHARACTER_LIMIT);
  const rest = count - named.length;
  const namesEn = joinNames(
    named.map((character) => character.name),
    'and',
  );
  const namesEl = joinNames(
    named.map((character) => character.name),
    'και',
  );
  const moreEn = rest > 0 ? `, and ${rest} more` : '';
  const moreEl = rest > 0 ? `, και άλλους ${rest}` : '';

  const headlineEn =
    count === 1 ? `${added[0].name} joins the roster` : `${count} new characters join the roster`;
  const headlineEl =
    count === 1
      ? `Ο ${added[0].name} μπαίνει στη λίστα`
      : `${count} νέοι χαρακτήρες μπαίνουν στη λίστα`;

  return {
    version,
    date,
    userVisible: true,
    headline: { en: headlineEn, el: headlineEl },
    summaryEn:
      `The nightly check of the game's data brought in ${
        count === 1 ? 'one new character' : `${count} new characters`
      }: ${namesEn}${moreEn}. ` +
      `${
        count === 1 ? 'It is' : 'They are'
      } already everywhere the app lists characters - search, Characters, Captain Coverage, both team builders and the ability filters - with ${
        count === 1 ? 'its' : 'their'
      } Captain Ability, special and potentials read and sorted like every other card. Nothing else in the app changed in this release.`,
    summaryEl:
      `Ο νυχτερινός έλεγχος των δεδομένων του παιχνιδιού έφερε ${
        count === 1 ? 'έναν νέο χαρακτήρα' : `${count} νέους χαρακτήρες`
      }: ${namesEl}${moreEl}. ` +
      `${
        count === 1 ? 'Βρίσκεται' : 'Βρίσκονται'
      } ήδη παντού όπου η εφαρμογή δείχνει χαρακτήρες - στην αναζήτηση, στα Characters, στο Captain Coverage, και στους δύο team builders και στα φίλτρα ικανοτήτων - με το Captain Ability, το special και τα potentials ${
        count === 1 ? 'του' : 'τους'
      } διαβασμένα και ταξινομημένα όπως κάθε άλλης κάρτας. Τίποτε άλλο δεν άλλαξε σε αυτή την έκδοση.`,
    added: named.map((character) => ({
      en: `${describeCharacter(character)}, with its Captain Ability, special, sailor ability and potentials read in - so it turns up in the ability filters and in Captain Coverage the same way every other character does.`,
      el: `${describeCharacterEl(character)}, με το Captain Ability, το special, το sailor ability και τα potentials του διαβασμένα - οπότε εμφανίζεται στα φίλτρα ικανοτήτων και στο Captain Coverage όπως κάθε άλλος χαρακτήρας.`,
    })),
    improved: [],
    fixed: [],
  };
}

function quote(value) {
  return `'${String(value).replace(/\\/gu, '\\\\').replace(/'/gu, "\\'")}'`;
}

function renderBullets(name, bullets, indent) {
  if (bullets.length === 0) {
    return `${indent}${name}: [],\n`;
  }

  const body = bullets
    .map(
      (bullet) =>
        `${indent}  {\n${indent}    en: ${quote(bullet.en)},\n${indent}    el: ${quote(bullet.el)},\n${indent}  },\n`,
    )
    .join('');

  return `${indent}${name}: [\n${body}${indent}],\n`;
}

export function renderEntry(entry) {
  const i = '  ';

  return (
    `${i}{\n` +
    `${i}  version: ${quote(entry.version)},\n` +
    `${i}  date: ${quote(entry.date)},\n` +
    `${i}  userVisible: ${entry.userVisible},\n` +
    `${i}  headline: {\n` +
    `${i}    en: ${quote(entry.headline.en)},\n` +
    `${i}    el: ${quote(entry.headline.el)},\n` +
    `${i}  },\n` +
    `${i}  summaryEn: ${quote(entry.summaryEn)},\n` +
    `${i}  summaryEl: ${quote(entry.summaryEl)},\n` +
    renderBullets('added', entry.added, `${i}  `) +
    renderBullets('improved', entry.improved, `${i}  `) +
    renderBullets('fixed', entry.fixed, `${i}  `) +
    `${i}},\n`
  );
}

export const ENTRIES_ANCHOR = 'export const WHATS_NEW_ENTRIES: readonly WhatsNewEntry[] = [\n';

export function insertEntry(source, rendered) {
  if (!source.includes(ENTRIES_ANCHOR)) {
    throw new Error(`Could not find the WHATS_NEW_ENTRIES anchor in ${WHATS_NEW_DATA_PATH}.`);
  }

  return source.replace(ENTRIES_ANCHOR, ENTRIES_ANCHOR + rendered);
}

const INSERT_MARKER = 'INSERT INTO characters';
const VALUES_MARKER = ') VALUES (';

function unquote(token) {
  const trimmed = token.trim().replace(/,$/u, '').trim();

  if (trimmed === 'NULL' || trimmed === '') {
    return null;
  }

  if (trimmed.startsWith("'") && trimmed.endsWith("'")) {
    return trimmed.slice(1, -1).replace(/''/gu, "'");
  }

  return trimmed;
}

/**
 * Reads `id, name, is_incomplete, type, primary_class, secondary_class,
 * classes_json, stars` out of every `INSERT INTO characters` block. The seed
 * writes one scalar per line, so a line walk is both cheaper and far less
 * brittle than one regex spanning a 25 MB file - and a name only ever escapes
 * a quote by doubling it, never with a newline.
 */
export function parseSeedCharacters(sql) {
  const characters = [];
  let cursor = 0;

  for (;;) {
    const insertAt = sql.indexOf(INSERT_MARKER, cursor);

    if (insertAt === -1) {
      break;
    }

    const valuesAt = sql.indexOf(VALUES_MARKER, insertAt);
    cursor = insertAt + INSERT_MARKER.length;

    if (valuesAt === -1) {
      continue;
    }

    const block = sql.slice(
      valuesAt + VALUES_MARKER.length,
      valuesAt + VALUES_MARKER.length + 4096,
    );
    const lines = block
      .split('\n')
      .map((line) => line.trim())
      .filter(Boolean);
    const id = Number.parseInt(unquote(lines[0] ?? '') ?? '', 10);
    const name = unquote(lines[1] ?? '');

    if (!Number.isFinite(id) || !name) {
      continue;
    }

    characters.push({
      id,
      name,
      type: unquote(lines[3] ?? ''),
      primaryClass: unquote(lines[4] ?? ''),
      secondaryClass: unquote(lines[5] ?? ''),
      stars: Number.parseInt(unquote(lines[7] ?? '') ?? '', 10),
    });

    cursor = valuesAt;
  }

  return characters;
}

/**
 * The committed preview, i.e. the dataset as it was before `data:import:all`
 * refreshed the working tree. A first release, a shallow clone or a missing
 * file all mean "no baseline", and a release must never fail for that - the
 * caller then writes a truthful quiet entry instead of an invented one.
 */
export function readPreviousCharacters({ appRoot, ref = 'HEAD' }) {
  try {
    return parseSeedCharacters(
      execFileSync('git', ['show', `${ref}:${SEED_DATA_PATH}`], {
        cwd: appRoot,
        encoding: 'utf8',
        maxBuffer: 256 * 1024 * 1024,
        // A missing baseline is an expected branch, not an incident: keep git's
        // "exists on disk, but not in HEAD" off the release log.
        stdio: ['ignore', 'pipe', 'ignore'],
      }),
    );
  } catch {
    return null;
  }
}

/**
 * How many commits landed since the previous release tag. The nightly data
 * chain releases straight off an unchanged `main`, so this is 0 for it and
 * non-zero for any release that follows merged work.
 */
export function countCommitsSince({ appRoot, previousTag }) {
  if (!previousTag) {
    return null;
  }

  try {
    return Number.parseInt(
      execFileSync('git', ['rev-list', '--count', `${previousTag}..HEAD`], {
        cwd: appRoot,
        encoding: 'utf8',
        stdio: ['ignore', 'pipe', 'ignore'],
      }).trim(),
      10,
    );
  } catch {
    return null;
  }
}

export function generateWhatsNewEntry({
  appRoot = process.cwd(),
  version,
  date,
  ref = 'HEAD',
  previousTag = null,
}) {
  if (!/^\d+\.\d+\.\d+$/u.test(String(version ?? ''))) {
    throw new Error(`--version must be X.Y.Z, got ${version}`);
  }

  const dataFile = path.join(appRoot, WHATS_NEW_DATA_PATH);

  if (!existsSync(dataFile)) {
    throw new Error(`${WHATS_NEW_DATA_PATH} does not exist under ${appRoot}.`);
  }

  const source = readFileSync(dataFile, 'utf8');

  if (hasEntryFor(source, version)) {
    return { written: false, reason: 'already-described', version, added: [] };
  }

  // Only the unattended data chain gets an auto-written entry. A release that
  // follows merged commits is somebody shipping code, and the only thing this
  // script can describe is which characters appeared - so for a code release it
  // would publish "nothing changed on any screen", in both languages, in the
  // app's own release history, and turn the loud red lane that catches a
  // forgotten entry into a green one telling players a falsehood. Refusing here
  // keeps that failure honest.
  const commitsSince = countCommitsSince({ appRoot, previousTag });

  if (commitsSince !== null && commitsSince > 0) {
    return { written: false, reason: 'code-release', version, added: [], commitsSince };
  }

  const seedFile = path.join(appRoot, SEED_DATA_PATH);
  const next = existsSync(seedFile) ? parseSeedCharacters(readFileSync(seedFile, 'utf8')) : [];
  const previous = readPreviousCharacters({ appRoot, ref });

  // No baseline means we cannot tell a new character from an existing one, so
  // we say nothing rather than announcing the whole roster as new.
  const { added } = previous === null ? { added: [] } : diffCharacters(previous, next);
  const entry = buildEntry({ version, date, added });

  writeFileSync(dataFile, insertEntry(source, renderEntry(entry)), 'utf8');

  return {
    written: true,
    reason: previous === null ? 'no-baseline' : 'generated',
    version,
    added: added.map((character) => character.name),
    userVisible: entry.userVisible,
  };
}

function parseArgs(argv) {
  const args = { appRoot: process.cwd(), ref: 'HEAD' };

  for (let index = 0; index < argv.length; index += 1) {
    const flag = argv[index];
    const value = argv[index + 1];

    if (flag === '--version') {
      args.version = value;
      index += 1;
    } else if (flag === '--date') {
      args.date = value;
      index += 1;
    } else if (flag === '--app-root') {
      args.appRoot = value;
      index += 1;
    } else if (flag === '--ref') {
      args.ref = value;
      index += 1;
    } else if (flag === '--previous-tag') {
      args.previousTag = value;
      index += 1;
    }
  }

  return args;
}

const invokedDirectly = process.argv[1] && process.argv[1].endsWith('generate-whats-new-entry.mjs');

if (invokedDirectly) {
  const args = parseArgs(process.argv.slice(2));
  const date = args.date ?? new Date().toISOString().slice(0, 10);

  try {
    const result = generateWhatsNewEntry({ ...args, date });

    if (!result.written && result.reason === 'code-release') {
      console.log(
        `[whats-new] ${result.version} follows ${result.commitsSince} commit(s); a code release describes itself. Not writing one.`,
      );
    } else if (!result.written) {
      console.log(`[whats-new] ${result.version} is already described; leaving it alone.`);
    } else if (result.added.length > 0) {
      console.log(
        `[whats-new] wrote the ${result.version} entry: ${result.added.length} new character(s) - ${result.added.join(', ')}.`,
      );
    } else {
      console.log(
        `[whats-new] wrote a quiet ${result.version} entry (${result.reason}); no new characters to announce.`,
      );
    }
  } catch (error) {
    console.error(`[whats-new] ${error.message}`);
    process.exitCode = 1;
  }
}
